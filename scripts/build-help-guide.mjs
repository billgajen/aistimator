#!/usr/bin/env node
/**
 * T-198: copy the help guide (Docs/help/*.md) into the web app, as the one
 * file "Ask Qolumns" reads (apps/web/src/lib/help/guide-pages.generated.ts).
 *
 *   pnpm help:build          write the file
 *   pnpm help:build --check  exit 1 when the file is not what Docs/help says
 *
 * Only the pages' own text is copied. Plan facts and "is it live" are not
 * filled in here: the web app fills them in from the plan definitions each
 * time it builds the guide, so they can never be out of date.
 *
 * A unit test (help-guide-t198) fails when the copy is stale.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const from = join(root, 'Docs', 'help')
const to = join(root, 'apps', 'web', 'src', 'lib', 'help', 'guide-pages.generated.ts')

export function helpPages() {
  return readdirSync(from)
    .filter((name) => /^\d{2}-[a-z0-9-]+\.md$/.test(name))
    .sort()
    .map((file) => ({ file, markdown: readFileSync(join(from, file), 'utf8').replace(/\r\n/g, '\n') }))
}

export function generated(pages = helpPages()) {
  return `/**
 * GENERATED by scripts/build-help-guide.mjs from Docs/help. Do not edit:
 * change the page in Docs/help and run \`pnpm help:build\`.
 */
import type { HelpPageSource } from '@qolumns/shared'

export const HELP_PAGES: HelpPageSource[] = ${JSON.stringify(pages, null, 2)}
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = generated()
  if (process.argv.includes('--check')) {
    const now = existsSync(to) ? readFileSync(to, 'utf8') : ''
    if (now !== text) {
      console.error('The help guide inside the web app is not what Docs/help says. Run: pnpm help:build')
      process.exit(1)
    }
    console.log('The help guide inside the web app matches Docs/help.')
  } else {
    writeFileSync(to, text)
    console.log(`Wrote ${helpPages().length} help pages to apps/web/src/lib/help/guide-pages.generated.ts`)
  }
}
