/**
 * The rows POST /api/services writes for a new service — pure. Pulled out of
 * the route (T-153) so the demo seed script creates its services exactly the
 * way the dashboard does. Relative imports only: scripts load this with tsx.
 */
import type { DocumentType, ServiceMediaConfig, WorkStepConfig, ExpectedSignalConfig, ServiceDraftConfig, AddonConfig, MultiplierConfig } from '@estimator/shared'
import { normalizeFieldOption } from './field-options'

export interface ServiceCreateBody {
  /** T-146: send quotes without business review (default false) */
  autoSend?: boolean
  /** T-147: hide the estimate until approved (default false = show, then confirm) */
  holdUntilApproved?: boolean
  name: string
  description?: string | null
  documentTypeDefault?: DocumentType
  scopeIncludes?: string[]
  scopeExcludes?: string[]
  defaultAssumptions?: string[]
  mediaConfig?: ServiceMediaConfig
  workSteps?: WorkStepConfig[]
  expectedSignals?: ExpectedSignalConfig[]
  draftConfig?: ServiceDraftConfig | null
  suggestedFields?: Array<{
    fieldId: string
    label: string
    type: string
    required: boolean
    options?: string[]
    helpText?: string
    criticalForPricing?: boolean
    mapsToSignal?: string
  }>
  // BUG-003 FIX: Type for pricingRules
  pricingRules?: {
    baseFee?: number
    minimumCharge?: number
    addons?: AddonConfig[]
    multipliers?: MultiplierConfig[]
    workSteps?: WorkStepConfig[]
  }
}

/** The services row (detection_keywords and prompt_context are generated by the worker) */
export function serviceInsertRow(tenantId: string, body: ServiceCreateBody, now = new Date()) {
  const { draftConfig, mediaConfig } = body
  return {
    tenant_id: tenantId,
    name: body.name.trim(),
    description: body.description || null,
    active: true,
    document_type_default: body.documentTypeDefault || 'instant_estimate',
    auto_send: body.autoSend === true,
    hold_until_approved: body.holdUntilApproved === true && body.autoSend !== true,
    scope_includes: body.scopeIncludes || [],
    scope_excludes: body.scopeExcludes || [],
    default_assumptions: body.defaultAssumptions || [],
    media_config: mediaConfig || { minPhotos: 1, maxPhotos: 8, photoGuidance: null },
    work_steps: body.workSteps || [],
    expected_signals: body.expectedSignals || [],
    draft_config: draftConfig || null,
    draft_config_version: draftConfig ? 1 : 0,
    draft_config_generated_at: draftConfig ? now.toISOString() : null,
  }
}

/** BUG-003 FIX: pricing rules with the actual values from the request (not hardcoded zeros) */
export function pricingRulesRow(tenantId: string, serviceId: string, body: ServiceCreateBody) {
  const p = body.pricingRules
  return {
    tenant_id: tenantId,
    service_id: serviceId,
    rules_json: {
      baseFee: p?.baseFee || 0,
      minimumCharge: p?.minimumCharge || 0,
      addons: p?.addons || [],
      multipliers: p?.multipliers || [],
      workSteps: p?.workSteps || body.workSteps || [],
    },
  }
}

/** The widget config with the suggested fields, or null when there are none */
export function widgetConfigRow(tenantId: string, serviceId: string, body: ServiceCreateBody) {
  // Fields can be in suggestedFields directly or inside draftConfig
  const fieldsToSave = body.suggestedFields || body.draftConfig?.suggestedFields
  if (!fieldsToSave || fieldsToSave.length === 0) return null
  const widgetFields = fieldsToSave.map((f) => ({
    fieldId: f.fieldId,
    label: f.label,
    type: f.type === 'dropdown' ? 'select' : f.type === 'boolean' ? 'boolean' : f.type,
    required: f.required || f.criticalForPricing || false,
    placeholder: f.helpText || undefined,
    helpText: f.helpText || undefined,
    criticalForPricing: f.criticalForPricing || false,
    mapsToSignal: f.mapsToSignal || undefined,
    // Convert options to {value, label} — the compiler sometimes emits
    // {label, value} objects instead of strings (hardcore-test finding: 500)
    ...(f.options && f.options.length > 0 && {
      options: f.options.map(normalizeFieldOption),
    }),
  }))
  return {
    tenant_id: tenantId,
    service_id: serviceId,
    config_json: {
      fields: widgetFields,
      files: body.mediaConfig || { minPhotos: 1, maxPhotos: 8, maxDocs: 3 },
    },
  }
}
